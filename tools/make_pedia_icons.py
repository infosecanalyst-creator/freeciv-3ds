#!/usr/bin/env python3
"""Cut Freeciv's Civilopedia icons into a sprite sheet for the 3DS client.

    python3 tools/make_pedia_icons.py <freeciv-source-dir>

Reads data/misc/{buildings,techs,governments}.spec (+ their .png grids) and
writes:
  3ds_port/gfx/pedia_<n>.png     one PNG per icon
  3ds_port/gfx/pedia.t3s         tex3ds atlas list (index = list order)
  3ds_port/source/pedia_icons.h  { "b.palace", 0 }, ... sorted by tag

Units are not included: their sprites are already in sprites.t3x.
Needs Pillow. The outputs are committed, so a normal build doesn't run this.
"""
import os
import re
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GFX = os.path.join(ROOT, "3ds_port", "gfx")
SRC = os.path.join(ROOT, "3ds_port", "source")


def parse_spec(path):
    """Yield (png_path, x, y, w, h, [tags]) for every grid tile in a .spec."""
    text = open(path, encoding="utf-8").read()
    gfx = re.search(r'^gfx\s*=\s*"([^"]+)"', text, re.M).group(1)
    for sec in re.finditer(r"^\[grid_\w+\](.*?)(?=^\[|\Z)", text, re.M | re.S):
        body = sec.group(1)

        def num(key, default=0):
            m = re.search(r"^\s*%s\s*=\s*(-?\d+)" % key, body, re.M)
            return int(m.group(1)) if m else default

        x0, y0, dx, dy = num("x_top_left"), num("y_top_left"), num("dx"), num("dy")
        pb = num("pixel_border")
        tiles = re.search(r"tiles\s*=\s*\{(.*?)\}", body, re.S).group(1)
        for line in tiles.splitlines():
            line = line.split(";")[0].strip()
            m = re.match(r"(\d+)\s*,\s*(\d+)\s*,\s*(.+)", line)
            if not m:
                continue
            row, col = int(m.group(1)), int(m.group(2))
            tags = re.findall(r'"([^"]+)"', m.group(3))
            yield gfx, x0 + (dx + pb) * col, y0 + (dy + pb) * row, dx, dy, tags


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    fc = sys.argv[1]
    for f in os.listdir(GFX):
        if f.startswith("pedia_") and f.endswith(".png"):
            os.remove(os.path.join(GFX, f))

    entries = []  # (tag, index)
    files = []
    for spec in ("buildings", "techs", "governments"):
        sheets = {}
        for gfx, x, y, w, h, tags in parse_spec(os.path.join(fc, "data", "misc", spec + ".spec")):
            if gfx not in sheets:
                sheets[gfx] = Image.open(os.path.join(fc, "data", gfx + ".png")).convert("RGBA")
            img = sheets[gfx].crop((x, y, x + w, y + h))
            idx = len(files)
            name = "pedia_%d.png" % idx
            img.save(os.path.join(GFX, name))
            files.append(name)
            for t in tags:
                entries.append((t, idx))

    with open(os.path.join(GFX, "pedia.t3s"), "w") as f:
        f.write("--atlas -f rgba8888 -z auto\n")
        for name in files:
            f.write(name + "\n")

    entries.sort()
    with open(os.path.join(SRC, "pedia_icons.h"), "w") as f:
        f.write("// Generated by tools/make_pedia_icons.py - do not edit.\n")
        f.write("// Freeciv graphic tag -> image index in romfs:/gfx/pedia.t3x.\n")
        f.write("typedef struct { const char *tag; int idx; } PediaIcon;\n")
        f.write("static const PediaIcon k_pedia_icons[] = {\n")
        for t, i in entries:
            f.write('    { "%s", %d },\n' % (t, i))
        f.write("};\n")
        f.write("#define PEDIA_ICON_COUNT %d\n" % len(entries))
    print("%d icons, %d tags" % (len(files), len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
