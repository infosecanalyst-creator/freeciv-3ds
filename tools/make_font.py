"""Bakes the UI font into a glyph atlas for the 3DS client.

Renders Inter (SIL OFL 1.1) with FreeType hinting at exact pixel sizes, so
text is drawn 1:1 on the 3DS screens instead of scaling one big font down.

  python3 tools/make_font.py [Inter-Medium.otf] [Inter-SemiBold.otf]

Writes 3ds_port/gfx/font.png (+ font.t3s) and 3ds_port/source/font_data.h.
Needs Pillow. Both outputs are committed, so a normal build doesn't need this.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/Inter-Medium.otf"
BOLD = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"

# (pixel size, weight) pairs; sizes >= 17 are the SemiBold title weight.
SIZES = [(11, REG), (12, REG), (13, REG), (14, REG), (15, REG), (16, REG),
         (18, BOLD), (20, BOLD), (24, BOLD)]
CODEPOINTS = list(range(32, 127)) + list(range(160, 256)) + \
             [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2192, 0x2190]
ATLAS_W, ATLAS_H = 1024, 1024

glyphs = []       # per size: list of (x, y, w, h, xoff, yoff, adv)
metrics = []      # per size: (line_height, ascent)
atlas = Image.new("LA", (ATLAS_W, ATLAS_H), (255, 0))
x = y = 0
row_h = 0
for px, path in SIZES:
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    metrics.append((asc + desc, asc))
    gl = []
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        bb = f.getbbox(ch)
        w, h = max(0, bb[2] - bb[0]), max(0, bb[3] - bb[1])
        if w == 0 or h == 0:
            gl.append((0, 0, 0, 0, 0, 0, adv))
            continue
        if x + w + 1 > ATLAS_W:
            x = 0; y += row_h + 1; row_h = 0
        if y + h > ATLAS_H:
            sys.exit("atlas full")
        g = Image.new("L", (w, h), 0)
        ImageDraw.Draw(g).text((-bb[0], -bb[1]), ch, font=f, fill=255)
        atlas.paste(Image.merge("LA", (Image.new("L", (w, h), 255), g)), (x, y))
        gl.append((x, y, w, h, bb[0], bb[1], adv))
        x += w + 1
        row_h = max(row_h, h)
    glyphs.append(gl)
    x = 0; y += row_h + 1; row_h = 0

used_h = y
H = 64
while H < used_h: H *= 2
atlas = atlas.crop((0, 0, ATLAS_W, H))
gfx = os.path.join(ROOT, "3ds_port", "gfx")
atlas.save(os.path.join(gfx, "font.png"))
with open(os.path.join(gfx, "font.t3s"), "w") as t:
    t.write("-f la8 -z auto\nfont.png\n")

with open(os.path.join(ROOT, "3ds_port", "source", "font_data.h"), "w") as o:
    o.write("// Generated by tools/make_font.py - Inter (SIL OFL 1.1), do not edit.\n")
    o.write("#pragma once\n#include <stdint.h>\n\n")
    o.write(f"#define FONT_ATLAS_W {ATLAS_W}\n#define FONT_ATLAS_H {H}\n")
    o.write(f"#define FONT_NSIZES {len(SIZES)}\n#define FONT_NGLYPHS {len(CODEPOINTS)}\n\n")
    o.write("typedef struct { uint16_t x, y; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; } FontGlyph;\n\n")
    o.write("static const uint8_t k_font_px[FONT_NSIZES] = { " + ", ".join(str(p) for p, _ in SIZES) + " };\n")
    o.write("static const uint8_t k_font_line[FONT_NSIZES] = { " + ", ".join(str(m[0]) for m in metrics) + " };\n")
    o.write("static const uint8_t k_font_ascent[FONT_NSIZES] = { " + ", ".join(str(m[1]) for m in metrics) + " };\n")
    o.write("static const uint16_t k_font_cps[FONT_NGLYPHS] = {\n")
    for i in range(0, len(CODEPOINTS), 16):
        o.write("    " + ", ".join(str(c) for c in CODEPOINTS[i:i+16]) + ",\n")
    o.write("};\n")
    o.write("static const FontGlyph k_font_glyphs[FONT_NSIZES][FONT_NGLYPHS] = {\n")
    for gl in glyphs:
        o.write("  {\n")
        for i in range(0, len(gl), 6):
            o.write("    " + " ".join("{%d,%d,%d,%d,%d,%d,%d}," % g for g in gl[i:i+6]) + "\n")
        o.write("  },\n")
    o.write("};\n")
print("atlas", ATLAS_W, "x", H, "used", used_h)
